#!/usr/bin/env bash
# Writes the Homebrew formula for one release to standard output, from the checksums of the files
# that release carries.
#
# Expects the following environment variables:
#   VERSION           the released version without the v prefix, e.g. 0.1.0
#   SHA_MACOS_ARM64   sha256 of the released worksheet-osx-arm64
#   SHA_MACOS_X64     sha256 of the released worksheet-osx-x64
#   SHA_LINUX_ARM64   sha256 of the released worksheet-linux-arm64
#   SHA_LINUX_X64     sha256 of the released worksheet-linux-x64
#
# The release carries bare executables rather than archives, so the formula installs the one file
# it downloaded under the name `worksheet`. Generating it needs nothing but a shell; `brew` is only
# needed to read it.
#
# Usage:
#   VERSION=0.1.0 SHA_MACOS_ARM64=... SHA_MACOS_X64=... SHA_LINUX_ARM64=... SHA_LINUX_X64=... \
#     scripts/generate-homebrew-formula.sh > dist/worksheet.rb
set -euo pipefail

version="${VERSION:?VERSION is required}"
sha_macos_arm64="${SHA_MACOS_ARM64:?SHA_MACOS_ARM64 is required}"
sha_macos_x64="${SHA_MACOS_X64:?SHA_MACOS_X64 is required}"
sha_linux_arm64="${SHA_LINUX_ARM64:?SHA_LINUX_ARM64 is required}"
sha_linux_x64="${SHA_LINUX_X64:?SHA_LINUX_X64 is required}"

base="https://github.com/d-led/worksheet.net/releases/download/v${version}"

cat <<EOF
# typed: false
# frozen_string_literal: true

# This file was generated by d-led/worksheet.net (scripts/generate-homebrew-formula.sh).
# Do not edit by hand; update via the release workflow or re-run the generator.
class Worksheet < Formula
  desc "The working day in one line, on projects and on the topics inside them"
  homepage "https://github.com/d-led/worksheet.net"
  version "${version}"
  license "MPL-2.0"

  on_macos do
    if Hardware::CPU.arm?
      url "${base}/worksheet-osx-arm64"
      sha256 "${sha_macos_arm64}"
    else
      url "${base}/worksheet-osx-x64"
      sha256 "${sha_macos_x64}"
    end
  end

  on_linux do
    if Hardware::CPU.arm?
      url "${base}/worksheet-linux-arm64"
      sha256 "${sha_linux_arm64}"
    else
      url "${base}/worksheet-linux-x64"
      sha256 "${sha_linux_x64}"
    end
  end

  def install
    # One file, named for the platform it was built for; the platform is the archive's business.
    binary = Dir["worksheet-*"].first
    bin.install binary => "worksheet"
  end

  # The application opens a window, so a test that ran it would hang. What is worth asserting is
  # that the download arrived intact and is executable.
  test do
    assert_predicate bin/"worksheet", :executable?
  end
end
EOF
